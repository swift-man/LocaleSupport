extension LocaleIdentifiers {
  static func flagCountryKey(for value: Self) -> String? {
    let description = value.displayDescription

    if let country = extractCountryKey(from: description) {
      return country
    }

    let language = extractLanguageKey(from: description)
    return defaultCountryKeyByLanguage[language]
  }

  static func extractLanguageKey(from description: String) -> String {
    let trimmedDescription = description.trimmingCharacters(in: .whitespacesAndNewlines)

    if defaultCountryKeyByLanguage[trimmedDescription] != nil {
      return trimmedDescription
    }

    let raw = trimmedDescription.components(separatedBy: "(").first ?? trimmedDescription
    return raw.trimmingCharacters(in: .whitespacesAndNewlines)
  }

  static func extractCountryKey(from description: String) -> String? {
    guard
      let openIndex = description.firstIndex(of: "("),
      let closeIndex = description[openIndex...].firstIndex(of: ")")
    else {
      return nil
    }

    let inside = String(description[description.index(after: openIndex)..<closeIndex])

    let ignoredParts: Set<String> = [
      "Latin",
      "Cyrillic",
      "Arabic",
      "Gurmukhi",
      "Simplified Han",
      "Traditional Han",
      "Tifinagh",
      "Computer"
    ]

    let parts = inside
      .components(separatedBy: ",")
      .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
      .filter { !ignoredParts.contains($0) }

    guard let country = parts.last, !country.isEmpty else {
      return nil
    }

    return country
  }

